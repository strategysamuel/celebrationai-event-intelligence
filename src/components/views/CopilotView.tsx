/**
 * Truthful Model Attribution Badge Formatter
 * Distinguishes requested model, actual upstream responding model,
 * alternate fallback model usage, and deterministic heuristic engine.
 */
export function getModelAttributionBadge(
  msg: {
    source?: 'gemini' | 'heuristic';
    requestedModel?: string;
    actualModel?: string | null;
    model?: string;
    isFallbackModel?: boolean;
    modelVersion?: string | null;
    fallbackType?: FallbackType;
  },
  configuredModel: string = 'gemini-3.8-flash'
): {
  label: string;
  subLabel?: string;
  tooltip: string;
  variant: 'primary-ai' | 'fallback-ai' | 'heuristic' | 'unreported-ai';
} {
  // 1. Heuristic fallback
  if (msg.source === 'heuristic' || msg.fallbackType === 'heuristic') {
    return {
      label: 'Deterministic Fallback Engine',
      tooltip: `Generated by server deterministic rule engine (requested: ${msg.requestedModel || configuredModel})`,
      variant: 'heuristic',
    };
  }

  const requested = msg.requestedModel || configuredModel;

  // 2. Missing upstream model metadata:
  // When actualModel is null or modelVersion is absent and actualModel was not reported
  const isMissingMetadata =
    msg.actualModel === null ||
    (msg.actualModel === undefined && (msg.modelVersion === null || msg.modelVersion === undefined) && !msg.model);

  if (isMissingMetadata) {
    return {
      label: `Live AI – requested ${requested}; serving model not reported`,
      tooltip: `Requested model: ${requested}. Upstream Gemini response did not report modelVersion metadata.`,
      variant: 'unreported-ai',
    };
  }

  // Determine fallback classification
  let fallbackType: FallbackType = msg.fallbackType || 'none';
  if (!msg.fallbackType) {
    if (msg.isFallbackModel) {
      fallbackType = 'alternate_model';
    } else if (msg.actualModel && msg.actualModel.trim().toLowerCase() !== requested.trim().toLowerCase()) {
      fallbackType = 'upstream_model_difference';
    } else {
      fallbackType = 'none';
    }
  }

  const actual = msg.actualModel || msg.modelVersion || msg.model || requested;

  // 3. Explicit alternate-model fallback
  if (fallbackType === 'alternate_model') {
    return {
      label: `Live AI: ${actual}`,
      subLabel: `[alternate fallback from ${requested}]`,
      tooltip: `Primary model (${requested}) failed. Served by alternate model: ${actual}.`,
      variant: 'fallback-ai',
    };
  }

  // 4. Upstream model or version difference
  if (fallbackType === 'upstream_model_difference') {
    return {
      label: `Live AI: ${actual}`,
      subLabel: `[upstream reported: ${actual}; requested: ${requested}]`,
      tooltip: `Requested: ${requested}. Upstream API reported serving model/version: ${actual}.`,
      variant: 'fallback-ai',
    };
  }

  // 5. Primary model confirmed by response metadata
  if (msg.modelVersion && actual.trim().toLowerCase() === requested.trim().toLowerCase()) {
    return {
      label: `Live AI (${actual})`,
      tooltip: `Serving model confirmed by upstream metadata: ${actual}`,
      variant: 'primary-ai',
    };
  }

  // 6. Legacy responses with only model field
  return {
    label: `Live AI (${actual})`,
    tooltip: `Serving model: ${actual}`,
    variant: 'primary-ai',
  };
}

export const CopilotView: React.FC<CopilotViewProps> = ({
  activeEvent,
  onApplyPlan,
  geminiModel,
}) => {
  const [messages, setMessages] = useState<CopilotChatMessage[]>([
    {
      id: 'init-msg',
      role: 'assistant',
      content: `### Welcome to CelebrationAI – Event Intelligence Copilot

I am your Principal AI Event Planning Copilot, ready to architect, optimize, and risk-evaluate your celebration.

Tell me about your event vision, or test with the competition benchmark:
> *"I am organizing a wedding in Chennai for 300 guests. My budget is Rs.15 lakhs and my wedding date is 15 February 2027. I prefer a traditional wedding."*

I will extract your structured requirements, calculate optimal category allocations, schedule backward milestones, and surface actionable recommendations.`,
      timestamp: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }),
      suggestedActions: [
        'Plan Chennai Wedding (300 guests, ₹15L, 15 Feb 2027)',
        'Optimize budget for Bangalore Birthday Gala (₹3.5L)',
        'Check critical timeline bottlenecks & vendor risks',
      ],
      source: 'heuristic',
      model: 'Deterministic Heuristic Engine',
      requestedModel: geminiModel,
      actualModel: 'Deterministic Heuristic Engine',
      isFallbackModel: false,
      modelVersion: null,
      fallbackType: 'heuristic',
    },
  ]);

  const [inputPrompt, setInputPrompt] = useState('');
  const [isLoading, setIsLoading] = useState(false);
  const [extractedDraft, setExtractedDraft] = useState<Partial<EventPlan> | null>(null);
  const [generatedProposal, setGeneratedProposal] = useState<EventPlan | null>(null);
  const [errorMsg, setErrorMsg] = useState<string | null>(null);

  const messagesEndRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    messagesEndRef.current?.scrollIntoView({ behavior: 'smooth' });
  }, [messages, isLoading]);

  const handleSendMessage = async (textToSend?: string) => {
    const text = (textToSend || inputPrompt).trim();
    if (!text || isLoading) return;

    setErrorMsg(null);
    const userMsg: CopilotChatMessage = {
      id: `user-${Date.now()}`,
      role: 'user',
      content: text,
      timestamp: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }),
    };

    const newHistory = [...messages, userMsg];
    setMessages(newHistory);
    setInputPrompt('');
    setIsLoading(true);

    try {
      const response = await apiClient.sendCopilotChat(
        newHistory.map((m) => ({ role: m.role, content: m.content })),
        activeEvent
      );

      const assistantMsg: CopilotChatMessage = {
        id: `asst-${Date.now()}`,
        role: 'assistant',
        content: response.reply,
        timestamp: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }),
        suggestedActions: response.suggestedActions,
        source: response.source,
        model: response.actualModel || response.model || response.requestedModel,
        requestedModel: response.requestedModel,
        actualModel: response.actualModel,
        isFallbackModel: response.isFallbackModel,
        modelVersion: response.modelVersion,
        fallbackType: response.fallbackType,
      };

      setMessages((prev) => [...prev, assistantMsg]);

      if (response.extractedRequirements) {
        setExtractedDraft(response.extractedRequirements);
      }
    } catch (err: any) {
      console.error('Copilot send error:', err);
      setErrorMsg(err.message || 'AI request timed out. Please try again.');
    } finally {
      setIsLoading(false);
    }
  };

  const handleGenerateFullPlan = async () => {
    setIsLoading(true);
    setErrorMsg(null);
    try {
      const promptContext =
        messages
          .filter((m) => m.role === 'user')
          .map((m) => m.content)
          .join('\n') || 'Wedding in Chennai for 300 guests with Rs.15 lakhs budget';

      const plan = await apiClient.generatePlan({
        prompt: promptContext,
        eventType: extractedDraft?.type || activeEvent.type,
        targetDate: extractedDraft?.eventDate || activeEvent.eventDate,
        guestCount: extractedDraft?.guestCount || activeEvent.guestCount,
        budget: extractedDraft?.totalBudget || activeEvent.totalBudget,
        currency: extractedDraft?.currency || activeEvent.currency,
      });

      setGeneratedProposal(plan);

      const planMeta = (plan as any).metadata;
      const source = planMeta?.source || (plan as any).source || 'gemini';
      const actualModel = planMeta?.actualModel ?? null;
      const requestedModel = planMeta?.requestedModel || geminiModel;
      const fallbackType = planMeta?.fallbackType || (planMeta?.isFallbackModel ? 'alternate_model' : 'none');
      const isFallbackModel = planMeta?.isFallbackModel ?? (fallbackType !== 'none');

      // Add assistant notification
      setMessages((prev) => [
        ...prev,
        {
          id: `asst-gen-${Date.now()}`,
          role: 'assistant',
          content: `### Complete Event Blueprint Generated!

I have synthesized a full operational proposal:
- **Title:** ${plan.name}
- **Budget Allocated:** ${plan.currency} ${plan.totalBudget.toLocaleString()} across ${plan.budgetAllocations.length} categories
- **Milestones:** ${plan.milestones.length} backward-scheduled gates
- **Tasks:** ${plan.tasks.length} execution deliverables with critical-path assignments
- **Vendors:** ${plan.vendors.length} candidate profiles scored with the 35/30/20/15 algorithm

Review the proposal in the right panel and click **"Apply to Active Event"** when ready.`,
          timestamp: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }),
          suggestedActions: [
            'Simulate 12 Lakhs Budget Cut',
            'Review Vendor Suitability Scores',
            'Audit Critical Timeline Path',
          ],
          source,
          requestedModel,
          actualModel,
          isFallbackModel,
          fallbackType,
          model: actualModel || requestedModel,
          modelVersion: planMeta?.modelVersion,
        },
      ]);
    } catch (err: any) {
      console.error('Plan generation failed:', err);
      setErrorMsg(err.message || 'Failed to generate full plan.');
    } finally {
      setIsLoading(false);
    }
  };

  const handleAdoptPlan = () => {
    if (!generatedProposal) return;
    onApplyPlan(generatedProposal);
    alert('Generated plan has been successfully applied to your active event portfolio!');
  };

  return (
    <div className="grid grid-cols-1 lg:grid-cols-12 gap-6 h-[calc(100vh-140px)]">
      {/* Left Chat Window (7 cols) */}
      <div className="lg:col-span-7 flex flex-col bg-white rounded-2xl border border-slate-200 shadow-sm overflow-hidden h-full">
        {/* Header */}
        <div className="p-4 bg-slate-900 text-white flex items-center justify-between border-b border-slate-800">
          <div className="flex items-center gap-2.5">
            <div className="p-2 rounded-lg bg-teal-500/20 text-teal-400 border border-teal-500/30">
              <Sparkles className="w-4 h-4" />
            </div>
            <div>
              <h2 className="text-sm font-bold tracking-tight">AI Planning Copilot</h2>
              <p className="text-[11px] text-slate-400">
                Configured: {geminiModel} • Dynamic Upstream Model Attribution
              </p>
            </div>
          </div>
          <button
            onClick={() => {
              setMessages([
                {
                  id: 'reset',
                  role: 'assistant',
                  content: 'Conversation reset. What event can I help you plan or optimize today?',
                  timestamp: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }),
                  source: 'heuristic',
                  model: 'Deterministic Heuristic Engine',
                  requestedModel: geminiModel,
                  actualModel: 'Deterministic Heuristic Engine',
                  isFallbackModel: false,
                  modelVersion: null,
                  fallbackType: 'heuristic',
                },
              ]);
              setExtractedDraft(null);
              setGeneratedProposal(null);
            }}
            className="p-1.5 rounded text-slate-400 hover:text-white hover:bg-slate-800 text-xs flex items-center gap-1 cursor-pointer"
            title="Reset conversation"
          >
            <RefreshCw className="w-3.5 h-3.5" />
            <span className="text-[11px]">Clear</span>
          </button>
        </div>

        {/* Message Thread */}
        <div className="flex-1 overflow-y-auto p-4 space-y-4 bg-slate-50/50">
          {messages.map((m) => {
            const isAsst = m.role === 'assistant';
            const badge = isAsst && m.source ? getModelAttributionBadge(m, geminiModel) : null;

            return (
              <div
                key={m.id}
                className={`flex gap-3 ${isAsst ? 'justify-start' : 'justify-end'}`}
              >
                {isAsst && (
                  <div className="w-7 h-7 rounded-lg bg-gradient-to-tr from-teal-500 to-blue-600 flex items-center justify-center text-white shrink-0 shadow-sm text-xs font-bold">
                    AI
                  </div>
                )}

                <div
                  className={`max-w-[85%] rounded-2xl p-4 text-xs leading-relaxed shadow-xs ${
                    isAsst
                      ? 'bg-white text-slate-800 border border-slate-200'
                      : 'bg-blue-600 text-white rounded-br-none'
                  }`}
                >
                  {isAsst && badge && (
                    <div className="mb-2">
                      <span
                        title={badge.tooltip}
                        className={`inline-flex items-center gap-1 px-2 py-0.5 rounded text-[10px] font-semibold border ${
                          badge.variant === 'primary-ai'
                            ? 'bg-teal-50 text-teal-700 border-teal-200'
                            : badge.variant === 'fallback-ai'
                            ? 'bg-amber-50 text-amber-800 border-amber-300'
                            : badge.variant === 'unreported-ai'
                            ? 'bg-blue-50 text-blue-700 border-blue-200'
                            : 'bg-slate-100 text-slate-700 border-slate-300'
                        }`}
                      >
                        {badge.variant === 'heuristic'
                          ? '⚡'
                          : badge.variant === 'fallback-ai'
                          ? '⚠️'
                          : badge.variant === 'unreported-ai'
                          ? 'ℹ️'
                          : '✨'}{' '}
                        <span>{badge.label}</span>
                        {badge.subLabel && (
                          <span className="text-[9px] font-normal opacity-85 ml-0.5">{badge.subLabel}</span>
                        )}
                      </span>
                    </div>
                  )}

                  <div className="prose prose-xs max-w-none space-y-2 whitespace-pre-wrap">
                    {m.content}
                  </div>

                  <div
                    className={`text-[10px] mt-2 text-right ${
                      isAsst ? 'text-slate-400' : 'text-blue-200'
                    }`}
                  >
                    {m.timestamp}
                  </div>

                  {/* Suggestion Chips */}
                  {isAsst && m.suggestedActions && m.suggestedActions.length > 0 && (
                    <div className="mt-3 pt-3 border-t border-slate-100 flex flex-wrap gap-1.5">
                      {m.suggestedActions.map((action, idx) => (
                        <button
                          key={idx}
                          onClick={() => handleSendMessage(action)}
                          className="px-2.5 py-1 rounded-full bg-slate-100 hover:bg-teal-50 hover:text-teal-700 hover:border-teal-300 border border-slate-200 text-[11px] font-medium text-slate-700 transition cursor-pointer text-left"
                        >
                          ⚡ {action}
                        </button>
                      ))}
                    </div>
                  )}
                </div>
              </div>
            );
          })}

          {isLoading && (
            <div className="flex gap-3 items-center text-slate-500 text-xs">
              <div className="w-7 h-7 rounded-lg bg-teal-500 flex items-center justify-center text-white shrink-0 animate-pulse text-xs font-bold">
                AI
              </div>
              <div className="p-3 bg-white rounded-xl border border-slate-200 flex items-center gap-2">
                <Loader2 className="w-4 h-4 text-teal-600 animate-spin" />
                <span>CelebrationAI is reasoning, calculating budget allocations, and structuring timeline...</span>
              </div>
            </div>
          )}

          {errorMsg && (
            <div className="p-3 rounded-xl bg-rose-50 border border-rose-200 text-rose-700 text-xs flex items-center gap-2">
              <AlertCircle className="w-4 h-4 shrink-0" />
              <span>{errorMsg}</span>
            </div>
          )}

          <div ref={messagesEndRef} />
        </div>

        {/* Input Bar */}
        <div className="p-3 bg-white border-t border-slate-200">
          <form
            onSubmit={(e) => {
              e.preventDefault();
              handleSendMessage();
            }}
            className="flex items-center gap-2"
          >
            <input
              type="text"
              value={inputPrompt}
              onChange={(e) => setInputPrompt(e.target.value)}
              placeholder="e.g., I want to plan a Chennai wedding for 300 guests with Rs.15L budget..."
              className="flex-1 text-xs px-3.5 py-2.5 rounded-xl border border-slate-300 focus:outline-none focus:ring-2 focus:ring-blue-500"
              disabled={isLoading}
            />
            <button
              type="submit"
              disabled={isLoading || !inputPrompt.trim()}
              className="px-4 py-2.5 rounded-xl bg-blue-600 hover:bg-blue-700 disabled:opacity-50 text-white font-semibold text-xs flex items-center gap-1.5 shadow transition cursor-pointer"
            >
              <Send className="w-3.5 h-3.5" />
              <span className="hidden sm:inline">Send</span>
            </button>
          </form>
        </div>
      </div>

      {/* Right Intelligence Panel (5 cols) */}
      <div className="lg:col-span-5 flex flex-col gap-4 overflow-y-auto">
        {/* Extracted Requirements Box */}
        <div className="bg-white rounded-2xl border border-slate-200 p-5 shadow-sm">
          <div className="flex items-center justify-between pb-3 border-b border-slate-100 mb-3">
            <div className="flex items-center gap-2">
              <Sliders className="w-4 h-4 text-blue-600" />
              <h3 className="text-xs font-bold uppercase tracking-wider text-slate-800">
                Extracted Event Requirements
              </h3>
            </div>
            <span className="text-[10px] font-semibold px-2 py-0.5 rounded-full bg-blue-50 text-blue-700 border border-blue-200">
              Live Structured Context
            </span>
          </div>

          <div className="space-y-2.5 text-xs">
            <div className="flex items-center justify-between p-2 rounded-lg bg-slate-50">
              <span className="text-slate-500">Event Type:</span>
              <span className="font-bold text-slate-900">
                {extractedDraft?.type || activeEvent.type}
              </span>
            </div>
            <div className="flex items-center justify-between p-2 rounded-lg bg-slate-50">
              <span className="text-slate-500">Date:</span>
              <span className="font-bold text-slate-900 font-mono">
                {extractedDraft?.eventDate || activeEvent.eventDate}
              </span>
            </div>
            <div className="flex items-center justify-between p-2 rounded-lg bg-slate-50">
              <span className="text-slate-500">Guest Headcount:</span>
              <span className="font-bold text-slate-900">
                {extractedDraft?.guestCount || activeEvent.guestCount} Attendees
              </span>
            </div>
            <div className="flex items-center justify-between p-2 rounded-lg bg-slate-50">
              <span className="text-slate-500">Budget Ceiling:</span>
              <span className="font-bold text-emerald-700 font-mono">
                {extractedDraft?.currency || activeEvent.currency}{' '}
                {(extractedDraft?.totalBudget || activeEvent.totalBudget).toLocaleString()}
              </span>
            </div>
          </div>

          {/* Action to Synthesize Full Blueprint */}
          <div className="mt-4 pt-3 border-t border-slate-100">
            <button
              onClick={handleGenerateFullPlan}
              disabled={isLoading}
              className="w-full py-2.5 rounded-xl bg-gradient-to-r from-teal-500 to-blue-600 hover:from-teal-400 hover:to-blue-500 disabled:opacity-50 text-white font-semibold text-xs flex items-center justify-center gap-2 shadow-sm transition cursor-pointer"
            >
              <Sparkles className="w-4 h-4" />
              <span>Synthesize Complete Event Blueprint</span>
            </button>
          </div>
        </div>

        {/* Generated Proposal Preview Card */}
        {generatedProposal && (
          <div className="bg-white rounded-2xl border-2 border-teal-500/50 p-5 shadow-lg relative">
            <div className="flex items-center justify-between mb-3">
              <span className="px-2.5 py-0.5 rounded-full text-[10px] font-bold bg-teal-500/20 text-teal-800 uppercase tracking-wide">
                Ready Proposal Preview
              </span>
              <span className="text-[10px] font-mono text-slate-400">
                Generated {new Date().toLocaleTimeString()}
              </span>
            </div>

            <h4 className="text-sm font-bold text-slate-900 mb-1">
              {generatedProposal.name}
            </h4>
            <p className="text-xs text-slate-500 mb-3">
              {generatedProposal.userPreferences}
            </p>

            <div className="grid grid-cols-2 gap-2 text-xs mb-4">
              <div className="p-2 rounded-lg bg-slate-50">
                <span className="text-[10px] text-slate-400 block font-semibold">
                  Allocations Total
                </span>
                <span className="font-bold text-slate-800">
                  {generatedProposal.budgetAllocations.length} Categories (100%)
                </span>
              </div>
              <div className="p-2 rounded-lg bg-slate-50">
                <span className="text-[10px] text-slate-400 block font-semibold">
                  Scheduled Tasks
                </span>
                <span className="font-bold text-slate-800">
                  {generatedProposal.tasks.length} Deliverables
                </span>
              </div>
            </div>

            <button
              onClick={handleAdoptPlan}
              className="w-full py-2.5 rounded-xl bg-emerald-600 hover:bg-emerald-700 text-white font-semibold text-xs flex items-center justify-center gap-2 shadow-md transition cursor-pointer"
            >
              <CheckCircle className="w-4 h-4" />
              <span>Apply Proposal to Active Event</span>
            </button>
          </div>
        )}
      </div>
    </div>
  );
};
